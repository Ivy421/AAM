"""
Depression_gripper_generation_loft.py

Run order:
    Depression_Completion.py
        -> repairModel_mesh.py
        -> Depression_gripper_generation_loft.py
        -> Depression_model_orient_bbox.py

Purpose:
    Add a one-piece PLA gripper onto the depression repair model top plane.

Main change compared with Depression_gripper_generation_v2.py:
    The gripper is no longer generated as three independent meshes
    (base_block + v_neck + grip_body). Instead, it is generated as ONE
    continuous rectangular loft mesh, following the same idea as
    hole_grip_generation.py:

        section 0 -> section 1 -> ... -> section N

    Only the first and last sections have caps. There are no internal caps
    between base / V-neck / grip body, so the gripper itself is one continuous
    shell before it is merged or boolean-unioned with the repair model.

Inputs expected in COMPLETION_DIR:
    model.stl      : generated by repairModel_mesh.py
    meta.npz       : generated by Depression_Completion.py, should contain:
                    - n_axis
                    - repair_point_center and top_plane_center
                    - side_n_mark, or u_axis/v_axis

Outputs:
    model_with_gripper.stl
    gripper_only.stl
    gripper_meta.npz

Geometry definition:
    - attach center   : [repair_point_center.x, repair_point_center.y, top_plane_center.z]
    - height direction: -n_axis, i.e. outward normal of top plane
    - width direction : u_axis
    - length direction: v_axis
    - base, V-neck and grip body are represented by one continuous loft.

Important unit setting:
    If current STL/PCD/meta are in meters, keep MM = 0.001.
    If current STL/PCD/meta are already in millimeters, set MM = 1.0.
"""

