BASE_LENGTH_V = 8.0 * MM

V_NECK_HEIGHT = 2.0 * MM
V_NECK_MIN_WIDTH_U = 1.0 * MM
V_NECK_MIN_LENGTH_V = 1.0 * MM
V_NECK_SECTION_NUM = 15

GRIP_BODY_HEIGHT = 15.0 * MM
GRIP_BODY_WIDTH_U = 3.0 * MM
GRIP_BODY_LENGTH_V = 3.0 * MM

