"""
hole_model_orient.py

Purpose
-------
Orient the full hole repair model with gripper into a standardized STL frame.

Input files are generated by previous steps:
    Hole_Completion.py      -> meta.npz, mark.json, model.pcd, defect/plane pcds
    repairModel_mesh.py     -> model.stl
    hole_grip.py            -> model_with_gripper.stl, gripper_only.stl, gripper_meta.npz

New coordinate definition
-------------------------
    +Z axis <- top_n_inward
    +Y axis <- side_n_inward
    +X axis <- right-hand rule, computed from +Y and +Z
    origin  <- bounding-box center of the whole model_with_gripper after rotation

Unit
----
Input STL is already in meters. No unit scaling is applied.

Main saved outputs
------------------
    model_with_gripper_oriented.stl
    model_oriented.stl                    # same full model, convenient alias
    model_repair_oriented.stl             # repair-only model if model.stl exists
    gripper_only_oriented.stl             # gripper-only model if gripper_only.stl exists
    orientation_meta.npz                  # contains T, R, t and transformed metadata
    orientation_meta.json                 # readable summary
"""

