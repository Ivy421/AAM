"""
hole_orientation.py

Purpose
-------
Standardize the pose of the hole repair model after the grip has been joined.

Input
-----
1) model_with_gripper.stl generated by hole_grip.py
2) meta / npz files saved by the previous completion / grip generation steps

Output
------
1) model_with_gripper_oriented.stl
2) hole_orientation_info.npz
3) hole_orientation_info.json
4) hole_orientation_info.txt
5) optional transformed point clouds / extra STL files

Coordinate convention after transformation
------------------------------------------
- The whole model means: repair model + gripper in model_with_gripper.stl.
- The new origin is the center of the AABB bounding box of the whole rotated model.
- side_n, the inward normal of the selected side face, is aligned to +Y.
- top_n, the inward normal of the top plane, is aligned to +Z.
- Unit is unchanged. If your STL is in meter, the output STL is still in meter.

Important note
--------------
Requirement 2 says the new origin is the bounding-box center. Therefore this code
centers the whole model at the AABB center after rotation. In this convention the
"top plane贴着 XOY" is interpreted as: the top plane is parallel to XOY and its
inward normal is +Z. The top plane is not forcibly shifted to z=0, because that
would break the bounding-box-center origin requirement.
"""

