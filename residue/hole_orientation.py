# CLI
# ============================================================
def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Orient hole model_with_gripper.stl to standardized frame.")
    parser.add_argument("--completion-dir", default=COMPLETION_DIR, help="Directory containing model_with_gripper.stl and meta npz files.")
    parser.add_argument("--input-stl", default=None, help="Input STL path. Default: completion_dir/model_with_gripper.stl")
    parser.add_argument("--output-stl", default=None, help="Output STL path. Default: completion_dir/model_with_gripper_oriented.stl")
    parser.add_argument("--meta", default=None, help="Optional explicit metadata npz path.")
    parser.add_argument("--top-n-key", default=TOP_N_KEY, help="Explicit top inward normal key in npz.")
    parser.add_argument("--side-n-key", default=SIDE_N_KEY, help="Explicit side inward normal key in npz.")
    parser.add_argument("--selected-side-key", default=SELECT_SIDE_KEY, help="Key in side_n_mark, e.g. max_u_outward / max_v_outward.")
    parser.add_argument("--visualize", action="store_true", help="Visualize oriented mesh and coordinate frame.")
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    orient_hole_model(
        completion_dir=args.completion_dir,
        input_stl_path=args.input_stl,
        output_stl_path=args.output_stl,
        meta_path=args.meta,
        top_n_key=args.top_n_key,
        side_n_key=args.side_n_key,
        selected_side_key=args.selected_side_key,
        visualize=args.visualize,
    )
