def normalize(v: np.ndarray) -> np.ndarray:
    v = np.asarray(v, dtype=float).reshape(3)
    n = np.linalg.norm(v)
    if n < 1e-12:
        raise ValueError(f"zero-length vector: {v}")
    return v / n


def unwrap_np_value(x):
    if isinstance(x, np.ndarray):
        if x.shape == ():
            return x.item()
        return x
    return x


def load_meta(meta_path: str):
    if not os.path.exists(meta_path):
        raise FileNotFoundError(f"Cannot find meta.npz: {meta_path}")

    data = np.load(meta_path, allow_pickle=True)

    if "n_axis" not in data.files:
        raise KeyError("meta.npz must contain n_axis")

    meta = {k: unwrap_np_value(data[k]) for k in data.files}
    meta["n_axis"] = normalize(np.asarray(meta["n_axis"], dtype=float))

    if "top_plane_center" not in meta:
        raise KeyError("meta.npz must contain top_plane_center")
    if "repair_point_center" not in meta:
        raise KeyError("meta.npz must contain repair_point_center")

    top_plane_center = np.asarray(meta["top_plane_center"], dtype=float).reshape(3)
    repair_point_center = np.asarray(meta["repair_point_center"], dtype=float).reshape(3)

    # 保持原代码逻辑：xy 来自 repair_point_center，z 来自 top_plane_center。
    # 注意：如果 repair_point_center 在极端缺陷中落在无实体区域，attach_center 仍可能悬空。
    attach_center = np.asarray([
        repair_point_center[0],
        repair_point_center[1],
        top_plane_center[2],
    ], dtype=float)

    meta["attach_center"] = attach_center
    return meta


def recover_uv_axes(meta: dict):
    """
    Recover u_axis and v_axis.

    Best case:
        meta.npz already contains u_axis and v_axis.

    Current completion scripts save outward normals directly:
        max_u_outward = +u_axis
        max_v_outward = +v_axis
        min_v_outward = -v_axis
    """
    n_axis = normalize(meta["n_axis"])

    if "u_axis" in meta and "v_axis" in meta:
        u_axis = normalize(np.asarray(meta["u_axis"], dtype=float))
        v_axis = normalize(np.asarray(meta["v_axis"], dtype=float))
        return u_axis, v_axis

    if "side_n_mark" not in meta:
        raise KeyError("meta.npz must contain either u_axis/v_axis or side_n_mark")

    side_n_mark = meta["side_n_mark"]
    if not isinstance(side_n_mark, dict):
        raise TypeError(f"side_n_mark should be dict, got {type(side_n_mark)}")

    if "max_u_outward" in side_n_mark:
        u_axis = normalize(np.asarray(side_n_mark["max_u_outward"], dtype=float))
    else:
        raise KeyError("Cannot recover u_axis from side_n_mark. Need max_u_outward.")

    if "max_v_outward" in side_n_mark:
        v_axis = normalize(np.asarray(side_n_mark["max_v_outward"], dtype=float))
    elif "min_v_outward" in side_n_mark:
        v_axis = -normalize(np.asarray(side_n_mark["min_v_outward"], dtype=float))
    else:
        v_axis = normalize(np.cross(n_axis, u_axis))

    # Re-orthogonalize.
    u_axis = normalize(u_axis - np.dot(u_axis, n_axis) * n_axis)
    v_axis = normalize(v_axis - np.dot(v_axis, n_axis) * n_axis - np.dot(v_axis, u_axis) * u_axis)

    if np.dot(np.cross(u_axis, v_axis), n_axis) < 0:
        v_axis = -v_axis

    return u_axis, v_axis


# =========================================================
# Continuous loft gripper construction
# =========================================================
def build_v_neck_sections(s0, s1):
    """
    Build V-neck sections.

    The size profile is:
        bottom: same as base block
        middle: narrow waist
        top   : same as grip body

    This produces V-shaped / dog-bone shrink-expand transition.
    """
    if V_NECK_SECTION_NUM < 3:
        n_sec = 3
    else:
        n_sec = int(V_NECK_SECTION_NUM)
    if n_sec % 2 == 0:
        n_sec += 1

    sections = []
    for i in range(n_sec):
        t = i / (n_sec - 1)
        s = s0 + t * (s1 - s0)

        if t <= 0.5:
            # base -> waist
            a = t / 0.5
            size_u = (1.0 - a) * BASE_WIDTH_U + a * V_NECK_MIN_WIDTH_U
            size_v = (1.0 - a) * BASE_LENGTH_V + a * V_NECK_MIN_LENGTH_V
        else:
            # waist -> grip body
            a = (t - 0.5) / 0.5
            size_u = (1.0 - a) * V_NECK_MIN_WIDTH_U + a * GRIP_BODY_WIDTH_U
            size_v = (1.0 - a) * V_NECK_MIN_LENGTH_V + a * GRIP_BODY_LENGTH_V

        sections.append((float(s), float(size_u), float(size_v)))

    return sections


def remove_duplicate_s_sections(sections, eps=1e-12):
    """
    Remove repeated sections with the same s value to avoid zero-length faces.
    If two sections have the same s, keep the latter one.
    """
    sections = sorted(sections, key=lambda x: x[0])
    cleaned = []
    for sec in sections:
        if cleaned and abs(sec[0] - cleaned[-1][0]) < eps:
            cleaned[-1] = sec
        else:
            cleaned.append(sec)
    return cleaned


def build_gripper_loft_sections():
    """
    Build one continuous section list for the whole gripper.

    s = 0 is the model top surface.
    s < 0 means the gripper is embedded into the repair model.
    s > 0 means the gripper grows outward along h_axis = -n_axis.

    This is the depression version of hole_grip's create_grip_local():
    one section list, one side wall connection, only two end caps.
    """
    vneck_s0 = BASE_HEIGHT
    vneck_s1 = BASE_HEIGHT + V_NECK_HEIGHT
    grip_s1 = vneck_s1 + GRIP_BODY_HEIGHT

    sections = []

    # Embedded base and lower base block. Keeping s=0 makes the contact plane explicit,
    # similar to hole_grip's x0=-embed_depth and x1=0.
    sections.append((-EMBED_DEPTH, BASE_WIDTH_U, BASE_LENGTH_V))
    sections.append((0.0, BASE_WIDTH_U, BASE_LENGTH_V))
    sections.append((BASE_HEIGHT, BASE_WIDTH_U, BASE_LENGTH_V))

    # V-neck transition. Exclude the first section because BASE_HEIGHT already exists.
    vneck_sections = build_v_neck_sections(vneck_s0, vneck_s1)
    sections.extend(vneck_sections[1:])

    # Grip body constant section. vneck_sections already ends at vneck_s1 with grip-body size.
    sections.append((grip_s1, GRIP_BODY_WIDTH_U, GRIP_BODY_LENGTH_V))

    return remove_duplicate_s_sections(sections), vneck_s0, vneck_s1, grip_s1


def create_rectangular_loft_trimesh(
    surface_center: np.ndarray,
    u_axis: np.ndarray,
    v_axis: np.ndarray,
    h_axis: np.ndarray,
    sections: list,
):
    """
    Create a continuous rectangular loft mesh from sections.

    sections:
        list of (s, size_u, size_v), sorted along h_axis.

    Local frame:
        local x equivalent = s along h_axis
        local y equivalent = u_axis, section width
        local z equivalent = v_axis, section length

    This follows the same topology as hole_grip_generation.py's
    create_rectangular_loft(): adjacent rectangles are connected directly;
    only start and end caps are added.
    """
    surface_center = np.asarray(surface_center, dtype=float).reshape(3)
    u_axis = normalize(u_axis)
    v_axis = normalize(v_axis)
    h_axis = normalize(h_axis)

    if len(sections) < 2:
        raise ValueError("Need at least two loft sections")

    sections = remove_duplicate_s_sections(sections)
    vertices = []
    faces = []

    for s, size_u, size_v in sections:
        center = surface_center + float(s) * h_axis
        hu = 0.5 * float(size_u)
        hv = 0.5 * float(size_v)

        # Same vertex order for every section.
        vertices.extend([
            center - hu * u_axis - hv * v_axis,
            center + hu * u_axis - hv * v_axis,
            center + hu * u_axis + hv * v_axis,
            center - hu * u_axis + hv * v_axis,
        ])

    # Side faces between adjacent sections.
    for i in range(len(sections) - 1):
        a = 4 * i
        b = 4 * (i + 1)
        quads = [
            [a + 0, a + 1, b + 1, b + 0],
            [a + 1, a + 2, b + 2, b + 1],
            [a + 2, a + 3, b + 3, b + 2],
            [a + 3, a + 0, b + 0, b + 3],
        ]
        for q in quads:
            faces.append([q[0], q[1], q[2]])
            faces.append([q[0], q[2], q[3]])

    # Start cap only.
    faces.append([0, 2, 1])
    faces.append([0, 3, 2])

    # End cap only.
    last = 4 * (len(sections) - 1)
    faces.append([last + 0, last + 1, last + 2])
    faces.append([last + 0, last + 2, last + 3])

    mesh = trimesh.Trimesh(
        vertices=np.asarray(vertices, dtype=float),
        faces=np.asarray(faces, dtype=np.int64),
        process=True,
    )
    mesh.remove_unreferenced_vertices()
    mesh.fix_normals()
    return mesh


def create_gripper_loft_mesh(
    surface_center: np.ndarray,
    u_axis: np.ndarray,
    v_axis: np.ndarray,
    h_axis: np.ndarray,
):
    """
    Create the whole gripper as a single continuous loft mesh.
    """
    sections, vneck_s0, vneck_s1, grip_s1 = build_gripper_loft_sections()
    gripper_tri = create_rectangular_loft_trimesh(
        surface_center=surface_center,
        u_axis=u_axis,
        v_axis=v_axis,
        h_axis=h_axis,
        sections=sections,
    )
    #gripper_o3d = trimesh_to_o3d(gripper_tri)
    return gripper_tri, sections, vneck_s0, vneck_s1, grip_s1


