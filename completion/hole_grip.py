def normalize(v: np.ndarray, eps: float = 1e-12) -> np.ndarray:
    v = np.asarray(v, dtype=float).reshape(3)
    n = np.linalg.norm(v)
    if n < eps:
        raise ValueError(f"zero-length vector: {v}")
    return v / n


def load_trimesh_mesh(path: Path) -> trimesh.Trimesh:
    obj = trimesh.load(str(path), force="mesh", process=True)
    if isinstance(obj, trimesh.Scene):
        meshes = [g for g in obj.geometry.values() if isinstance(g, trimesh.Trimesh)]
        if not meshes:
            raise RuntimeError(f"No mesh found in scene: {path}")
        mesh = trimesh.util.concatenate(meshes)
    else:
        mesh = obj

    if mesh.vertices.shape[0] == 0 or mesh.faces.shape[0] == 0:
        raise RuntimeError(f"Empty mesh: {path}")

    #mesh.remove_duplicate_faces()
    #mesh.remove_degenerate_faces()
    mesh.remove_unreferenced_vertices()
    mesh.fix_normals()
    return mesh


def normalize_plane(plane_model: np.ndarray) -> np.ndarray:
    """
    plane_model = [a, b, c, d], ax + by + cz + d = 0.
    Return [n_unit, d_scaled].
    """
    p = np.asarray(plane_model, dtype=float).reshape(4)
    n = p[:3]
    d = float(p[3])
    s = np.linalg.norm(n)
    if s < 1e-12:
        raise ValueError("invalid plane normal")
    return np.r_[n / s, d / s]


def orient_plane_to_normal(plane_model: np.ndarray, target_normal: np.ndarray) -> np.ndarray:
    """Orient plane normal to target_normal."""
    p = normalize_plane(plane_model)
    target_normal = normalize(target_normal)
    if np.dot(p[:3], target_normal) < 0:
        p = -p
    return p


def load_meta_and_mark(meta_path: Path, mark_path: Path) -> Tuple[Dict[str, np.ndarray], Dict[str, str]]:
    if not meta_path.exists():
        raise FileNotFoundError(f"Cannot find meta file: {meta_path}")
    if not mark_path.exists():
        raise FileNotFoundError(f"Cannot find mark file: {mark_path}")

    raw = np.load(str(meta_path), allow_pickle=True)
    meta = {k: raw[k] for k in raw.files}

    with open(str(mark_path), "r", encoding="utf-8") as f:
        mark = json.load(f)

    required = [
        "plane1_model", "plane2_model", "n1", "n2",
        "defect1_center", "defect2_center",
        "object_center",
    ]
    for k in required:
        if k not in meta:
            raise KeyError(f"meta.npz does not contain required key: {k}")

    return meta, mark


def get_top_side_ids(mark: Dict[str, str]) -> Tuple[int, int]:
    if mark.get("top") == "defect_pcd1":
        top_id = 1
    elif mark.get("top") == "defect_pcd2":
        top_id = 2
    else:
        raise ValueError(f"Unknown mark['top']: {mark.get('top')}")

    if mark.get("side") == "defect_pcd1":
        side_id = 1
    elif mark.get("side") == "defect_pcd2":
        side_id = 2
    else:
        raise ValueError(f"Unknown mark['side']: {mark.get('side')}")

    if top_id == side_id:
        raise ValueError(f"top and side should be different, got {mark}")

    return top_id, side_id


