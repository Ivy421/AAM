def transform_plane_model(plane: np.ndarray, R: np.ndarray, t: np.ndarray) -> np.ndarray:
    """
    Transform plane coefficients [a,b,c,d] under p' = R p + t.
    Original: n dot p + d = 0
    New:      n' dot p' + d' = 0
    n' = R n
    d' = d - n' dot t
    """
    plane = np.asarray(plane, dtype=np.float64).reshape(-1)
    if plane.size < 4:
        raise ValueError("plane model should be [a,b,c,d]")
    n = normalize(plane[:3], "plane normal")
    d = float(plane[3])
    n_new = normalize(R @ n, "transformed plane normal")
    d_new = d - float(np.dot(n_new, t))
    return np.array([n_new[0], n_new[1], n_new[2], d_new], dtype=np.float64)


def maybe_transform_meta_value(key: str, value: Any, R: np.ndarray, T: np.ndarray) -> Any:
    """
    Best-effort transformation for common metadata.

    - point / center / origin / vertex arrays are transformed by full T.
    - normal / axis / vector arrays are transformed by R only.
    - plane_model [a,b,c,d] is transformed as plane coefficients.
    - side_n_mark dict is transformed by R for each vector.
    """
    key_l = key.lower()
    value = unwrap_np_value(value)

    if isinstance(value, dict):
        out = {}
        for k, v in value.items():
            arr = np.asarray(v)
            if arr.size == 3:
                out[str(k)] = apply_R_to_vectors(arr.reshape(3), R)
            else:
                out[str(k)] = v
        return out

    try:
        arr = np.asarray(value)
    except Exception:
        return value

    # Keep strings / objects unchanged.
    if arr.dtype.kind in {"U", "S", "O"}:
        return value

    # Plane model.
    if "plane_model" in key_l or key_l.endswith("_plane"):
        if arr.size == 4:
            try:
                return transform_plane_model(arr.reshape(4), R, T[:3, 3])
            except Exception:
                return value

    # Single normal / axis / vector.
    vector_words = ["normal", "axis", "_n", "n_", "vec", "vector"]
    point_words = ["point", "center", "origin", "vertex", "vertices", "corner", "attach", "base"]

    if arr.shape == (3,) or arr.size == 3:
        arr3 = arr.reshape(3).astype(np.float64)
        if any(w in key_l for w in vector_words) and not any(w in key_l for w in point_words):
            return apply_R_to_vectors(arr3, R)
        if any(w in key_l for w in point_words):
            return apply_T_to_points(arr3, T)
        return value

    # Nx3 point arrays.
    if arr.ndim == 2 and arr.shape[1] == 3:
        if any(w in key_l for w in point_words) or "pcd" in key_l or "points" in key_l:
            return apply_T_to_points(arr.astype(np.float64), T)
        if any(w in key_l for w in vector_words):
            return apply_R_to_vectors(arr.astype(np.float64), R)

    return value


def save_transformed_meta(meta: Dict[str, Any], R: np.ndarray, T: np.ndarray, output_path: Path) -> None:
    transformed: Dict[str, Any] = {}
    for key, value in meta.items():
        transformed[key] = maybe_transform_meta_value(key, value, R, T)

    # np.savez can store dict as object arrays. Use allow_pickle=True when reading.
    np.savez(output_path, **transformed)
    print(f"[saved] transformed meta: {output_path}")


