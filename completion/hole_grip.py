def plane_intersection_line(plane_a: np.ndarray, plane_b: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """
    Return one point p0 and unit direction d of two plane intersection line.
    Planes should be normalized [nx, ny, nz, d].
    """
    p1 = normalize_plane(plane_a)
    p2 = normalize_plane(plane_b)
    n1, d1 = p1[:3], p1[3]
    n2, d2 = p2[:3], p2[3]

    line_dir = np.cross(n1, n2)
    line_dir = normalize(line_dir)

    # Solve:
    # n1 · p = -d1
    # n2 · p = -d2
    # line_dir · p = 0
    A = np.vstack([n1, n2, line_dir])
    b = np.array([-d1, -d2, 0.0], dtype=float)
    p0 = np.linalg.solve(A, b)
    return p0, line_dir


def read_pcd_points(path: Path) -> np.ndarray:
    if not path.exists():
        raise FileNotFoundError(f"Cannot find point cloud: {path}")
    pcd = o3d.io.read_point_cloud(str(path))
    pts = np.asarray(pcd.points, dtype=float)
    if pts.shape[0] == 0:
        raise RuntimeError(f"Empty point cloud: {path}")
    return pts


def estimate_edge_midpoint_from_side_pcd(
    side_pts: np.ndarray,
    top_plane: np.ndarray,
    side_plane: np.ndarray,
    edge_band: float,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, float]]:
    """
    Find the midpoint of the top-side intersection edge using side defect points.

    1. Compute exact top-side plane intersection line.
    2. Select side defect points close to the top plane.
    3. Project those selected points onto the line and take median coordinate.
    4. Return edge_mid on the exact line.
    """
    top_plane = normalize_plane(top_plane)
    side_plane = normalize_plane(side_plane)
    p0, edge_axis = plane_intersection_line(top_plane, side_plane)

    n_top, d_top = top_plane[:3], top_plane[3]
    dist_to_top = np.abs(side_pts @ n_top + d_top)

    mask = dist_to_top <= edge_band
    selected = side_pts[mask]

    # Fallback: take nearest 20% points if band is too strict.
    if selected.shape[0] < 5:
        k = max(5, int(0.20 * side_pts.shape[0]))
        idx = np.argsort(dist_to_top)[:k]
        selected = side_pts[idx]

    t = (selected - p0) @ edge_axis
    t_mid = float(np.median(t))
    edge_mid = p0 + t_mid * edge_axis

    info = {
        "selected_edge_points": int(selected.shape[0]),
        "edge_band": float(edge_band),
        "t_min": float(np.min(t)),
        "t_max": float(np.max(t)),
        "t_mid": float(t_mid),
    }
    return edge_mid, edge_axis, info


