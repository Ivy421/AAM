# Loft / mesh construction in local frame
# =========================================================
def create_offset_rectangular_loft_local(sections: List[Tuple[float, float, float, float, float]]) -> trimesh.Trimesh:
    """
    Create a rectangular loft mesh in local coordinates.

    sections = [(x, y_center, z_center, width_y, thickness_z), ...]

    Only the first and last sections are capped. Adjacent sections are connected
    directly, avoiding internal caps.
    """
    if len(sections) < 2:
        raise ValueError("Need at least two sections")

    sections = sorted(sections, key=lambda s: s[0])

    vertices = []
    faces = []

    for x, yc, zc, wy, tz in sections:
        vertices.extend([
            [x, yc - wy / 2.0, zc - tz / 2.0],
            [x, yc + wy / 2.0, zc - tz / 2.0],
            [x, yc + wy / 2.0, zc + tz / 2.0],
            [x, yc - wy / 2.0, zc + tz / 2.0],
        ])

    for i in range(len(sections) - 1):
        a = 4 * i
        b = 4 * (i + 1)
        quads = [
            [a + 0, a + 1, b + 1, b + 0],
            [a + 1, a + 2, b + 2, b + 1],
            [a + 2, a + 3, b + 3, b + 2],
            [a + 3, a + 0, b + 0, b + 3],
        ]
        for q in quads:
            faces.append([q[0], q[1], q[2]])
            faces.append([q[0], q[2], q[3]])

    # start cap
    faces.append([0, 2, 1])
    faces.append([0, 3, 2])

    # end cap
    last = 4 * (len(sections) - 1)
    faces.append([last + 0, last + 1, last + 2])
    faces.append([last + 0, last + 2, last + 3])

    mesh = trimesh.Trimesh(
        vertices=np.asarray(vertices, dtype=float),
        faces=np.asarray(faces, dtype=np.int64),
        process=True,
    )
    mesh.remove_unreferenced_vertices()
    mesh.fix_normals()
    return mesh


def create_box_local(center: Tuple[float, float, float], extents: Tuple[float, float, float]) -> trimesh.Trimesh:
    mesh = trimesh.creation.box(extents=np.asarray(extents, dtype=float))
    mesh.apply_translation(np.asarray(center, dtype=float))
    mesh.remove_unreferenced_vertices()
    mesh.fix_normals()
    return mesh


def create_breakaway_neck_local(
    y_offset: float,
    root_z: float,
    end_z: float,
) -> Tuple[trimesh.Trimesh, np.ndarray]:
    """
    Create one neck from side-top edge to wide base.
    The V notch reduces width along local y direction.
    """
    if FRACTURE_DISTANCE <= 0.25 * MM:
        raise ValueError("FRACTURE_DISTANCE too small")
    if FRACTURE_DISTANCE >= NECK_LENGTH:
        raise ValueError("FRACTURE_DISTANCE must be smaller than NECK_LENGTH")

    x0 = -EMBED_DEPTH
    x1 = 0.0
    x2 = max(FRACTURE_DISTANCE - NOTCH_LENGTH / 2.0, 0.05 * MM)
    x3 = FRACTURE_DISTANCE
    x4 = min(FRACTURE_DISTANCE + NOTCH_LENGTH / 2.0, NECK_LENGTH - 0.05 * MM)
    x5 = NECK_LENGTH

    def z_at(x: float) -> float:
        a = np.clip((x - x1) / max(x5 - x1, 1e-12), 0.0, 1.0)
        return (1.0 - a) * root_z + a * end_z

    waist_width = NECK_WIDTH_Y * NOTCH_WIDTH_RATIO
    sections = [
        (x0, y_offset, root_z, NECK_WIDTH_Y, NECK_THICKNESS_Z),
        (x1, y_offset, root_z, NECK_WIDTH_Y, NECK_THICKNESS_Z),
        (x2, y_offset, z_at(x2), NECK_WIDTH_Y, NECK_THICKNESS_Z),
        (x3, y_offset, z_at(x3), waist_width, NECK_THICKNESS_Z),
        (x4, y_offset, z_at(x4), NECK_WIDTH_Y, NECK_THICKNESS_Z),
        (x5, y_offset, end_z, NECK_WIDTH_Y, NECK_THICKNESS_Z),
    ]
    mesh = create_offset_rectangular_loft_local(sections)
    return mesh, np.asarray(sections, dtype=float)


def boolean_union_safe(meshes: List[trimesh.Trimesh], label: str) -> trimesh.Trimesh:
    """Try boolean union, fallback to concatenate."""
    try:
        out = trimesh.boolean.union(meshes, engine="manifold")
        if out is not None and len(out.vertices) > 0:
            #out.remove_duplicate_faces()
            #out.remove_degenerate_faces()
            out.remove_unreferenced_vertices()
            out.fix_normals()
            print(f"[OK] boolean union succeeded: {label}")
            return out
    except Exception as e:
        print(f"[WARN] boolean union failed for {label}: {e}")

    print(f"[WARN] fallback to concatenate: {label}")
    out = trimesh.util.concatenate(meshes)
    out.remove_unreferenced_vertices()
    out.fix_normals()
    return out


def create_grip_local() -> Tuple[trimesh.Trimesh, Dict[str, np.ndarray]]:
    """
    Create the whole local grip:
        two breakaway necks + wide low base + grasp cube.
    """
    base_start_x = NECK_LENGTH - BASE_OVERLAP_WITH_NECK
    base_center_x = base_start_x + BASE_LENGTH_X / 2.0
    base_center_z = BASE_THICKNESS_Z / 2.0

    base = create_box_local(
        center=(base_center_x, 0.0, base_center_z),
        extents=(BASE_LENGTH_X, BASE_WIDTH_Y, BASE_THICKNESS_Z),
    )

    cube_center_x = base_start_x + BASE_LENGTH_X * GRASP_CUBE_CENTER_X_RATIO
    cube_center_z = BASE_THICKNESS_Z + GRASP_CUBE_HEIGHT_Z / 2.0
    cube = create_box_local(
        center=(cube_center_x, 0.0, cube_center_z),
        extents=(GRASP_CUBE_LENGTH_X, GRASP_CUBE_WIDTH_Y, GRASP_CUBE_HEIGHT_Z),
    )

    # Two necks connect to the front edge region of the base.
    root_z = base_center_z
    end_z = base_center_z
    y_offsets = np.array([-LINK_PAIR_OFFSET, LINK_PAIR_OFFSET], dtype=float)

    neck_meshes = []
    neck_sections = []
    for yoff in y_offsets:
        neck, sections = create_breakaway_neck_local(y_offset=float(yoff), root_z=root_z, end_z=end_z)
        neck_meshes.append(neck)
        neck_sections.append(sections)

    parts = [base, cube] + neck_meshes
    if BOOLEAN_UNION_GRIP_PARTS:
        grip = boolean_union_safe(parts, "grip parts")
    else:
        grip = trimesh.util.concatenate(parts)
        grip.remove_unreferenced_vertices()
        grip.fix_normals()

    info = {
        "base_start_x": np.asarray(base_start_x),
        "base_center": np.asarray([base_center_x, 0.0, base_center_z]),
        "cube_center": np.asarray([cube_center_x, 0.0, cube_center_z]),
        "y_offsets": y_offsets,
        "neck_sections_left": neck_sections[0],
        "neck_sections_right": neck_sections[1],
    }
    return grip, info


