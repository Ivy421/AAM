def make_frame_matrix(origin: np.ndarray, x_axis: np.ndarray, y_axis: np.ndarray, z_axis: np.ndarray) -> np.ndarray:
    T = np.eye(4)
    T[:3, 0] = normalize(x_axis)
    T[:3, 1] = normalize(y_axis)
    T[:3, 2] = normalize(z_axis)
    T[:3, 3] = np.asarray(origin, dtype=float).reshape(3)
    return T


