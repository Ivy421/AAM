"""
Depression_gripper_generation_v2.py

Run order:
    Depression_Completion.py
        -> repairModel_mesh.py
        -> Depression_gripper_generation_v2.py
        -> Depression_model_orient_bbox.py

Purpose:
    Add a one-piece PLA gripper onto the depression repair model top plane.
    Compared with the previous version, the twist-off neck is no longer a tiny
    cuboid. It is a continuous V / dog-bone transition section connecting the
    lower base block and the upper grip body.

Inputs expected in COMPLETION_DIR:
    model.stl      : generated by repairModel_mesh.py
    meta.npz       : generated by Depression_Completion.py, should contain:
                    - n_axis
                    - repair_top_center or top_plane_center
                    - side_n_mark, or u_axis/v_axis

Outputs:
    model_with_gripper.stl
    gripper_only.stl
    gripper_meta.npz

Geometry definition:
    - attach center   : repair_top_center if available, otherwise top_plane_center
    - height direction: -n_axis, i.e. outward normal of top plane
    - length direction: v_axis
    - width direction : u_axis
    - twist-off V-neck starts 2 mm above model top surface
    - no round / chamfer / fillet operation

Important unit setting:
    If current STL/PCD/meta are in meters, keep MM = 0.001.
    If current STL/PCD/meta are already in millimeters, set MM = 1.0.
"""

import os
import numpy as np
import open3d as o3d


# =========================================================
# User config
# =========================================================
COMPLETION_DIR = r"E:\HKUSTGZ\AAM\construction\data\completion_result\depression"
INPUT_STL = os.path.join(COMPLETION_DIR, "model.stl")
META_PATH = os.path.join(COMPLETION_DIR, "meta.npz")
OUTPUT_STL = os.path.join(COMPLETION_DIR, "model_with_gripper.stl")
GRIPPER_ONLY_STL = os.path.join(COMPLETION_DIR, "gripper_only.stl")
GRIPPER_META = os.path.join(COMPLETION_DIR, "gripper_meta.npz")

# Unit conversion: millimeter -> current model unit.
MM = 0.001

# Small overlap into the model to avoid numerical gap at top surface.

##  base section: 6 × 9 mm
##        ↓ 线性收缩
##  waist section: 3 × 5 mm
##        ↓ 线性放大
##  grip section: 8 × 12 mm

## u,v参数要按比例调整 6:9 = 4:6 这样

EMBED_DEPTH = 0.0 * MM

BASE_HEIGHT = 2.0 * MM
BASE_WIDTH_U = 6.0 * MM
BASE_LENGTH_V = 9.0 * MM

V_NECK_HEIGHT = 3.0 * MM
V_NECK_MIN_WIDTH_U = 2 * MM
V_NECK_MIN_LENGTH_V = 3 * MM
V_NECK_SECTION_NUM = 15

GRIP_BODY_HEIGHT = 15.0 * MM
GRIP_BODY_WIDTH_U = 6.0 * MM
GRIP_BODY_LENGTH_V = 9.0 * MM

VISUALIZE = True

# =========================================================
# Basic utils
# =========================================================
def normalize(v: np.ndarray) -> np.ndarray:
    v = np.asarray(v, dtype=float).reshape(3)
    n = np.linalg.norm(v)
    if n < 1e-12:
        raise ValueError(f"zero-length vector: {v}")
    return v / n


def unwrap_np_value(x):
    if isinstance(x, np.ndarray):
        if x.shape == ():
            return x.item()
        return x
    return x


def load_meta(meta_path: str):
    if not os.path.exists(meta_path):
        raise FileNotFoundError(f"Cannot find meta.npz: {meta_path}")

    data = np.load(meta_path, allow_pickle=True)

    if "n_axis" not in data.files:
        raise KeyError("meta.npz must contain n_axis")

    meta = {k: unwrap_np_value(data[k]) for k in data.files}
    meta["n_axis"] = normalize(np.asarray(meta["n_axis"], dtype=float))


    if "top_plane_center" in meta:
        top_plane_center = np.asarray(meta["top_plane_center"], dtype=float).reshape(3)
        #attach_key = "top_plane_center"
    if 'repair_point_center' in meta:
        repair_point_center = meta['repair_point_center']

    # 这里有一个潜在的问题，attach center有可能因为缺陷模型的极端畸形而周围没有点云，是在半空的
    attach_center = np.asarray([repair_point_center[0], repair_point_center[1],top_plane_center[2] ])

    meta["attach_center"] = attach_center
    #meta["attach_center_key"] = attach_key
    return meta


def recover_uv_axes(meta: dict):
    """
    Recover u_axis and v_axis.

    Best case:
        meta.npz already contains u_axis and v_axis.

    Current Depression_Completion.py case:
        side_n_mark is saved. For CORNER_MODE = max_u_max_v, current code stores:
            side_n_mark['max_u_outward'] = v_axis
            side_n_mark['max_v_outward'] = u_axis
    """
    n_axis = normalize(meta["n_axis"])

    if "u_axis" in meta and "v_axis" in meta:
        u_axis = normalize(np.asarray(meta["u_axis"], dtype=float))
        v_axis = normalize(np.asarray(meta["v_axis"], dtype=float))
        return u_axis, v_axis

    if "side_n_mark" not in meta:
        raise KeyError("meta.npz must contain either u_axis/v_axis or side_n_mark")

    side_n_mark = meta["side_n_mark"]
    if not isinstance(side_n_mark, dict):
        raise TypeError(f"side_n_mark should be dict, got {type(side_n_mark)}")

    if "max_v_outward" in side_n_mark:
        u_axis = normalize(np.asarray(side_n_mark["max_v_outward"], dtype=float))
    elif "min_v_outward" in side_n_mark:
        u_axis = normalize(np.asarray(side_n_mark["min_v_outward"], dtype=float))
    else:
        raise KeyError("Cannot recover u_axis from side_n_mark. Need max_v_outward or min_v_outward.")

    if "max_u_outward" in side_n_mark:
        v_axis = normalize(np.asarray(side_n_mark["max_u_outward"], dtype=float))
    elif "min_u_outward" in side_n_mark:
        v_axis = normalize(np.asarray(side_n_mark["min_u_outward"], dtype=float))
    else:
        v_axis = normalize(np.cross(n_axis, u_axis))

    # Re-orthogonalize.
    u_axis = normalize(u_axis - np.dot(u_axis, n_axis) * n_axis)
    v_axis = normalize(v_axis - np.dot(v_axis, n_axis) * n_axis - np.dot(v_axis, u_axis) * u_axis)

    if np.dot(np.cross(u_axis, v_axis), n_axis) < 0:
        v_axis = -v_axis

    return u_axis, v_axis


