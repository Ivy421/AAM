# Mesh conversion / merge / boolean
# =========================================================
def merge_meshes(meshes):
    if all(isinstance(m, trimesh.Trimesh) for m in meshes):
        merged = trimesh.util.concatenate(meshes)
        merged = clean_trimesh(merged)
        return merged

    merged = o3d.geometry.TriangleMesh()
    for m in meshes:
        merged += m
    merged.remove_duplicated_vertices()
    merged.remove_duplicated_triangles()
    merged.remove_degenerate_triangles()
    merged.remove_unreferenced_vertices()
    merged.compute_vertex_normals()
    return merged


def o3d_to_trimesh(mesh_o3d):
    v = np.asarray(mesh_o3d.vertices)
    f = np.asarray(mesh_o3d.triangles)
    return trimesh.Trimesh(vertices=v, faces=f, process=True)


def trimesh_to_o3d(mesh_tri):
    mesh_o3d = o3d.geometry.TriangleMesh()
    mesh_o3d.vertices = o3d.utility.Vector3dVector(np.asarray(mesh_tri.vertices))
    mesh_o3d.triangles = o3d.utility.Vector3iVector(np.asarray(mesh_tri.faces, dtype=np.int32))
    mesh_o3d.remove_duplicated_vertices()
    mesh_o3d.remove_duplicated_triangles()
    mesh_o3d.remove_degenerate_triangles()
    mesh_o3d.remove_unreferenced_vertices()
    mesh_o3d.compute_vertex_normals()
    return mesh_o3d


def boolean_union(mesh_a, mesh_b):
    try:
        union = trimesh.boolean.union(
            [mesh_a, mesh_b],
            engine="manifold",
        )
    except ModuleNotFoundError as exc:
        print(f"Boolean union skipped: {exc}. Falling back to mesh concatenate.")
        return merge_meshes([mesh_a, mesh_b])
    except BaseException as exc:
        print(f"Boolean union failed: {exc}. Falling back to mesh concatenate.")
        return merge_meshes([mesh_a, mesh_b])

    if union is None:
        print("Boolean union returned None. Falling back to mesh concatenate.")
        return merge_meshes([mesh_a, mesh_b])

    return union

    union = trimesh.boolean.union(
        [mesh_a, mesh_b],
        engine="manifold" ) # 如果不可用，改成 "blender"

    if union is None:
        raise RuntimeError("Boolean union failed")

    return union

