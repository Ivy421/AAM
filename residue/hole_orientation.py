def orient_hole_model(
    completion_dir: str = COMPLETION_DIR,
    input_stl_path: Optional[str] = None,
    output_stl_path: Optional[str] = None,
    meta_path: Optional[str] = None,
    top_n_key: Optional[str] = TOP_N_KEY,
    side_n_key: Optional[str] = SIDE_N_KEY,
    selected_side_key: Optional[str] = SELECT_SIDE_KEY,
    visualize: bool = VISUALIZE,
) -> Dict[str, Any]:
    completion_dir_p = Path(completion_dir)

    input_stl = Path(input_stl_path) if input_stl_path else completion_dir_p / INPUT_STL_NAME
    output_stl = Path(output_stl_path) if output_stl_path else completion_dir_p / OUTPUT_STL_NAME

    if not input_stl.exists():
        raise FileNotFoundError(f"Cannot find input STL: {input_stl}")

    meta, loaded_meta_paths = load_npz_files(completion_dir_p, meta_path)

    top_n_src, top_n_used_key = find_top_n(meta, explicit_key=top_n_key)
    side_n_src, side_n_used_key, side_source_type = find_side_n(
        meta,
        explicit_key=side_n_key,
        selected_side_key=selected_side_key,
        convert_outward_to_inward=CONVERT_OUTWARD_SIDE_MARK_TO_INWARD,
    )

    # Construct rotation.
    R, basis_info = rotation_align_side_top_to_yz(side_n_src, top_n_src)

    # Read whole model with gripper and rotate first.
    mesh, vertices = read_mesh_vertices(input_stl)
    vertices_rot = (R @ vertices.T).T

    bbox_min_before, bbox_max_before, bbox_center_before, bbox_size_before = compute_bbox(vertices)
    bbox_min_rot, bbox_max_rot, bbox_center_rot, bbox_size_rot = compute_bbox(vertices_rot)

    # New origin = AABB center of the whole rotated model.
    t = -bbox_center_rot
    T = make_T(R, t)

    vertices_out = vertices_rot + t.reshape(1, 3)
    bbox_min_after, bbox_max_after, bbox_center_after, bbox_size_after = compute_bbox(vertices_out)

    mesh.vertices = o3d.utility.Vector3dVector(vertices_out)
    mesh.compute_vertex_normals()

    output_stl.parent.mkdir(parents=True, exist_ok=True)
    ok = o3d.io.write_triangle_mesh(str(output_stl), mesh, write_ascii=False)
    if not ok:
        raise RuntimeError(f"Failed to write oriented STL: {output_stl}")

    top_n_after = normalize(R @ top_n_src, "top_n_after")
    side_n_after = normalize(R @ side_n_src, "side_n_after")

    # Transform optional extra geometry.
    extra_saved = transform_extra_geometries(completion_dir_p, input_stl, T)

    # Save transformed metadata.
    transformed_meta_path = completion_dir_p / TRANSFORMED_META_NPZ_NAME
    try:
        save_transformed_meta(meta, R, T, transformed_meta_path)
    except Exception as e:
        print(f"[warn] failed to save transformed meta: {e}")
        transformed_meta_path = None  # type: ignore[assignment]

    orientation_info: Dict[str, Any] = {
        "completion_dir": str(completion_dir_p),
        "input_stl": str(input_stl),
        "output_stl": str(output_stl),
        "loaded_meta_paths": loaded_meta_paths,
        "top_n_used_key": top_n_used_key,
        "side_n_used_key": side_n_used_key,
        "side_source_type": side_source_type,
        "selected_side_key_config": selected_side_key,
        "unit_scale": 1.0,
        "unit_note": "No unit conversion is applied. Input meter -> output meter.",
        "target_side_n": TARGET_SIDE_N,
        "target_top_n": TARGET_TOP_N,
        "top_n_src": top_n_src,
        "side_n_src_inward": side_n_src,
        "top_n_after": top_n_after,
        "side_n_after": side_n_after,
        "R": R,
        "t": t,
        "T": T,
        "bbox_min_before": bbox_min_before,
        "bbox_max_before": bbox_max_before,
        "bbox_center_before": bbox_center_before,
        "bbox_size_before": bbox_size_before,
        "bbox_min_rot_before_centering": bbox_min_rot,
        "bbox_max_rot_before_centering": bbox_max_rot,
        "bbox_center_rot_before_centering": bbox_center_rot,
        "bbox_size_rot_before_centering": bbox_size_rot,
        "bbox_min_after": bbox_min_after,
        "bbox_max_after": bbox_max_after,
        "bbox_center_after": bbox_center_after,
        "bbox_size_after": bbox_size_after,
        "basis_info": basis_info,
        "extra_saved": extra_saved,
        "transformed_meta_path": str(transformed_meta_path) if transformed_meta_path else None,
    }

    # Save NPZ.
    npz_path = completion_dir_p / ORIENTATION_NPZ_NAME
    np.savez(
        npz_path,
        T=T,
        R=R,
        t=t,
        top_n_src=top_n_src,
        side_n_src_inward=side_n_src,
        top_n_after=top_n_after,
        side_n_after=side_n_after,
        target_top_n=TARGET_TOP_N,
        target_side_n=TARGET_SIDE_N,
        bbox_min_before=bbox_min_before,
        bbox_max_before=bbox_max_before,
        bbox_center_before=bbox_center_before,
        bbox_size_before=bbox_size_before,
        bbox_min_after=bbox_min_after,
        bbox_max_after=bbox_max_after,
        bbox_center_after=bbox_center_after,
        bbox_size_after=bbox_size_after,
        top_n_used_key=np.array(top_n_used_key),
        side_n_used_key=np.array(side_n_used_key),
        side_source_type=np.array(side_source_type),
        input_stl=np.array(str(input_stl)),
        output_stl=np.array(str(output_stl)),
        loaded_meta_paths=np.array(loaded_meta_paths, dtype=object),
    )

    # Save JSON.
    json_path = completion_dir_p / ORIENTATION_JSON_NAME
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(to_jsonable(orientation_info), f, ensure_ascii=False, indent=2)

    # Save TXT summary.
    txt_path = completion_dir_p / ORIENTATION_TXT_NAME
    with open(txt_path, "w", encoding="utf-8") as f:
        f.write("hole_orientation.py result\n")
        f.write("==========================\n\n")
        f.write(f"input_stl  = {input_stl}\n")
        f.write(f"output_stl = {output_stl}\n")
        f.write(f"npz        = {npz_path}\n")
        f.write(f"json       = {json_path}\n")
        f.write(f"meta used  = {loaded_meta_paths}\n\n")
        f.write(f"top_n_used_key  = {top_n_used_key}\n")
        f.write(f"side_n_used_key = {side_n_used_key}\n")
        f.write(f"side_source_type = {side_source_type}\n\n")
        f.write("R =\n")
        f.write(np.array2string(R, precision=12, suppress_small=False))
        f.write("\n\nt =\n")
        f.write(np.array2string(t, precision=12, suppress_small=False))
        f.write("\n\nT =\n")
        f.write(np.array2string(T, precision=12, suppress_small=False))
        f.write("\n\ncheck normals:\n")
        f.write(f"R @ top_n_src  = {top_n_after}\n")
        f.write(f"R @ side_n_src = {side_n_after}\n")
        f.write("\ncheck bbox after orientation:\n")
        f.write(f"bbox_min_after    = {bbox_min_after}\n")
        f.write(f"bbox_max_after    = {bbox_max_after}\n")
        f.write(f"bbox_center_after = {bbox_center_after}\n")
        f.write(f"bbox_size_after   = {bbox_size_after}\n")

    print("\n========== hole orientation finished ==========")
    print(f"[saved] oriented STL: {output_stl}")
    print(f"[saved] T/R/t npz:    {npz_path}")
    print(f"[saved] json:         {json_path}")
    print(f"[saved] txt:          {txt_path}")
    print(f"top_n source key:     {top_n_used_key}")
    print(f"side_n source key:    {side_n_used_key}")
    print(f"side source type:     {side_source_type}")
    print(f"R @ top_n_src:        {top_n_after}")
    print(f"R @ side_n_src:       {side_n_after}")
    print(f"bbox center after:    {bbox_center_after}")
    print("Unit: unchanged, no meter/mm conversion applied.")
    print("==============================================\n")

    if visualize:
        frame = o3d.geometry.TriangleMesh.create_coordinate_frame(size=max(float(bbox_size_after.max()), 1e-3) * 0.25)
        o3d.visualization.draw_geometries([mesh, frame])

    return orientation_info


