"""
hole_grip.py

Purpose
-------
Generate a new hole-repair gripper from scratch, without applying any model
frame/orientation transform in this file.

Design requirement
------------------
1. Read the existing hole repair model and metadata:
       model.stl
       meta.npz
       mark.json
       defect_pcd1.pcd / defect_pcd2.pcd
2. Use trimesh to process meshes.
3. Generate the grip with rectangular loft sections, similar to the depression
   gripper loft idea.
4. The grip grows from the side defect plane, but its growth direction is
       h_axis = -side_n
   where side_n is the inward normal stored in meta.npz.
5. The two neck-to-repair connection points are located on the side-bottom edge,
   i.e. the intersection line between top plane and side plane. The two points
   are placed at edge_mid +/- LINK_PAIR_OFFSET along the edge direction.
6. Grip shape:
       two breakaway necks -> wide low base -> grasp cube.
7. This script does NOT rotate or re-orient the model. It keeps the original
   coordinate frame unchanged.
8. All geometry parameters and computed frame data are saved to gripper_meta.npz
   for later synchronized model/grip rotation.

Assumptions
-----------
- model.stl and point clouds are in meters, as generated by Hole_Completion.py
  and repairModel_mesh.py.
- Design parameters are written in millimeters and multiplied by MM = 0.001.
- meta.npz stores n1/n2 as inward normals.
"""

