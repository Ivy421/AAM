def find_existing_file(candidates: Iterable[Path], what: str) -> Path:
    tried = []
    for p in candidates:
        p = Path(p)
        tried.append(str(p))
        if p.exists():
            return p
    raise FileNotFoundError(f"Cannot find {what}. Tried:\n" + "\n".join(tried))


def collect_npz_paths(completion_dir: Path, user_meta_path: Optional[str] = None) -> List[Path]:
    candidates: List[Path] = []
    if user_meta_path:
        candidates.append(Path(user_meta_path))

    common_names = [
        "hole_grip_info.npz",
        "grip_info.npz",
        "model_with_gripper_info.npz",
        "meta_with_gripper.npz",
        "meta.npz",
        "completion_meta.npz",
    ]
    candidates.extend([completion_dir / name for name in common_names])

    # 兼容之前代码中可能出现的 completion_dir + 'meta.npz' 少斜杠问题。
    candidates.append(Path(str(completion_dir) + "meta.npz"))

    # 最后扫描目录中所有 npz，按名字优先级排序。
    if completion_dir.exists():
        all_npz = sorted(completion_dir.glob("*.npz"))
        priority_words = ("grip", "with_gripper", "meta", "completion")
        all_npz = sorted(
            all_npz,
            key=lambda p: (
                0 if any(w in p.name.lower() for w in priority_words) else 1,
                p.name.lower(),
            ),
        )
        candidates.extend(all_npz)

    # 去重但保持顺序。
    seen = set()
    out = []
    for p in candidates:
        s = str(p)
        if s not in seen:
            seen.add(s)
            out.append(p)
    return out


def load_npz_files(completion_dir: Path, user_meta_path: Optional[str] = None) -> Tuple[Dict[str, Any], List[str]]:
    """
    Load all available npz metadata files and merge them.
    Later files do not overwrite earlier keys unless the earlier value is missing.
    """
    meta: Dict[str, Any] = {}
    loaded_paths: List[str] = []

    for p in collect_npz_paths(completion_dir, user_meta_path):
        if not p.exists():
            continue
        try:
            data = np.load(p, allow_pickle=True)
        except Exception as e:
            print(f"[warn] skip npz {p}: {e}")
            continue

        loaded_paths.append(str(p))
        for key in data.files:
            if key not in meta:
                meta[key] = unwrap_np_value(data[key])

    if not loaded_paths:
        raise FileNotFoundError(
            "No npz metadata found. Please make sure hole_grip.py saved one of: "
            "hole_grip_info.npz / grip_info.npz / model_with_gripper_info.npz / meta.npz"
        )

    return meta, loaded_paths


def get_array3_from_meta(meta: Dict[str, Any], keys: Iterable[str]) -> Tuple[Optional[np.ndarray], Optional[str]]:
    for key in keys:
        if key in meta:
            arr = np.asarray(meta[key], dtype=np.float64)
            if arr.shape == (3,):
                return arr, key
            if arr.size == 3:
                return arr.reshape(3), key
    return None, None


def find_top_n(meta: Dict[str, Any], explicit_key: Optional[str] = None) -> Tuple[np.ndarray, str]:
    if explicit_key:
        if explicit_key not in meta:
            raise KeyError(f"TOP_N_KEY={explicit_key!r} not found in meta keys: {list(meta.keys())}")
        return normalize(np.asarray(meta[explicit_key], dtype=np.float64), explicit_key), explicit_key

    candidate_keys = [
        "top_n",
        "top_n_axis",
        "top_normal",
        "top_normal_inward",
        "top_n_inward",
        "top_plane_n",
        "top_plane_normal",
        "n_axis",  # 你之前的补全代码里 n_axis 通常就是顶面 inward normal
    ]
    top_n, used_key = get_array3_from_meta(meta, candidate_keys)
    if top_n is not None:
        return normalize(top_n, used_key), used_key  # type: ignore[arg-type]

    # 兜底：从 top_plane_model = [a,b,c,d] 取法线。
    if "top_plane_model" in meta:
        plane = np.asarray(meta["top_plane_model"], dtype=np.float64).reshape(-1)
        if plane.size >= 3:
            return normalize(plane[:3], "top_plane_model[:3]"), "top_plane_model[:3]"

    raise KeyError(
        "Cannot find top_n. Please save top_n/top_n_axis/top_n_inward/n_axis "
        "in hole_grip.py metadata, or set TOP_N_KEY manually."
    )


def normalize_side_key_name(key: str) -> str:
    key = str(key)
    if key.endswith("_outward") or key.endswith("_inward"):
        return key
    # selected_side_key 可能保存为 max_u / min_v，需要补全 outward。
    if key in {"min_u", "max_u", "min_v", "max_v"}:
        return key + "_outward"
    return key


def find_selected_side_key(meta: Dict[str, Any], side_n_mark: Dict[str, Any]) -> Optional[str]:
    selected_key_candidates = [
        "selected_side_key",
        "grip_side_key",
        "attach_side_key",
        "side_key",
        "side_name",
        "selected_side_name",
        "grip_side_name",
        "attach_side_name",
    ]

    for k in selected_key_candidates:
        if k in meta:
            raw = unwrap_np_value(meta[k])
            if isinstance(raw, bytes):
                raw = raw.decode("utf-8")
            key = normalize_side_key_name(str(raw))
            if key in side_n_mark:
                return key

    return None


def load_side_n_mark(meta: Dict[str, Any]) -> Optional[Dict[str, np.ndarray]]:
    if "side_n_mark" not in meta:
        return None

    raw = unwrap_np_value(meta["side_n_mark"])
    if not isinstance(raw, dict):
        raise TypeError(f"side_n_mark should be dict, got {type(raw)}")

    out: Dict[str, np.ndarray] = {}
    for k, v in raw.items():
        out[str(k)] = normalize(np.asarray(v, dtype=np.float64), f"side_n_mark[{k}]")
    return out


def find_side_n(
    meta: Dict[str, Any],
    explicit_key: Optional[str] = None,
    selected_side_key: Optional[str] = None,
    convert_outward_to_inward: bool = True,
) -> Tuple[np.ndarray, str, str]:
    """
    Returns
    -------
    side_n_inward, used_key, source_type
    """
    if explicit_key:
        if explicit_key not in meta:
            raise KeyError(f"SIDE_N_KEY={explicit_key!r} not found in meta keys: {list(meta.keys())}")
        return normalize(np.asarray(meta[explicit_key], dtype=np.float64), explicit_key), explicit_key, "direct"

    direct_keys = [
        "side_n",
        "side_n_axis",
        "side_normal",
        "side_normal_inward",
        "side_n_inward",
        "selected_side_n",
        "selected_side_normal",
        "grip_side_n",
        "grip_side_normal",
        "attach_side_n",
        "attach_side_normal",
    ]
    side_n, used_key = get_array3_from_meta(meta, direct_keys)
    if side_n is not None:
        return normalize(side_n, used_key), used_key, "direct"  # type: ignore[arg-type]

    side_n_mark = load_side_n_mark(meta)
    if side_n_mark is None:
        raise KeyError(
            "Cannot find side_n. Please save side_n/side_n_axis/side_n_inward in hole_grip.py, "
            "or save side_n_mark plus selected_side_key/grip_side_key."
        )

    if selected_side_key is not None:
        key = normalize_side_key_name(selected_side_key)
        if key not in side_n_mark:
            raise KeyError(
                f"SELECT_SIDE_KEY={selected_side_key!r} not found in side_n_mark. "
                f"Available keys: {list(side_n_mark.keys())}"
            )
    else:
        key = find_selected_side_key(meta, side_n_mark)
        if key is None:
            if len(side_n_mark) == 1:
                key = next(iter(side_n_mark.keys()))
            else:
                raise KeyError(
                    "side_n_mark has multiple candidates, but no selected side key was found.\n"
                    f"Available side_n_mark keys: {list(side_n_mark.keys())}\n"
                    "Please either:\n"
                    "  1) save side_n / side_n_axis / side_n_inward directly in hole_grip.py, or\n"
                    "  2) save selected_side_key / grip_side_key, or\n"
                    "  3) set SELECT_SIDE_KEY at the top of this file."
                )

    side = normalize(side_n_mark[key], f"side_n_mark[{key}]")
    source_type = "side_n_mark"

    # side_n_mark 在你之前代码里通常保存的是 outward normal。
    # 当前要求是 inward normal，所以默认取负号。
    if convert_outward_to_inward and "outward" in key.lower():
        side = -side
        source_type = "side_n_mark_outward_converted_to_inward"
    elif "inward" in key.lower():
        source_type = "side_n_mark_inward"

    return normalize(side, "side_n_inward"), key, source_type


# ============================================================
# Rotation construction
# ============================================================
def rotation_align_side_top_to_yz(side_n_src: np.ndarray, top_n_src: np.ndarray) -> Tuple[np.ndarray, Dict[str, np.ndarray]]:
    """
    Build R so that:
        R @ side_n_src == +Y
        R @ top_n_src  == +Z

    The source basis is built as:
        z_src = top_n_src
        y_src = side_n_src projected onto the plane perpendicular to z_src
        x_src = y_src cross z_src

    This produces a right-handed source basis [x_src, y_src, z_src].
    """
    z_src = normalize(top_n_src, "top_n_src")
    y_raw = normalize(side_n_src, "side_n_src")

    y_src = y_raw - np.dot(y_raw, z_src) * z_src
    y_norm = np.linalg.norm(y_src)
    if y_norm < 1e-8:
        raise ValueError(
            "side_n_src and top_n_src are nearly parallel. "
            "A side normal should be perpendicular to top normal."
        )
    y_src = y_src / y_norm

    x_src = normalize(np.cross(y_src, z_src), "x_src = side x top")

    # Re-orthogonalize z to remove numeric drift and guarantee right-handed basis.
    z_src = normalize(np.cross(x_src, y_src), "z_src reorthogonalized")

    S = np.column_stack([x_src, y_src, z_src])
    Tgt = np.eye(3, dtype=np.float64)

    R = Tgt @ S.T

    # Numerical cleanup.
    U, _, Vt = np.linalg.svd(R)
    R = U @ Vt
    if np.linalg.det(R) < 0:
        U[:, -1] *= -1
        R = U @ Vt

    basis_info = {
        "x_src": x_src,
        "y_src": y_src,
        "z_src": z_src,
        "side_n_src_projected": y_src,
        "top_n_src_reorthogonalized": z_src,
        "side_n_dst_check": R @ y_raw,
        "top_n_dst_check": R @ normalize(top_n_src, "top_n_src_original"),
    }
    return R, basis_info


def compute_bbox(vertices: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    vertices = np.asarray(vertices, dtype=np.float64)
    bbox_min = vertices.min(axis=0)
    bbox_max = vertices.max(axis=0)
    bbox_center = 0.5 * (bbox_min + bbox_max)
    bbox_size = bbox_max - bbox_min
    return bbox_min, bbox_max, bbox_center, bbox_size


