# Basic utils
# =========================================================
def normalize(v: np.ndarray) -> np.ndarray:
    v = np.asarray(v, dtype=float).reshape(3)
    n = np.linalg.norm(v)
    if n < 1e-12:
        raise ValueError(f"zero-length vector: {v}")
    return v / n


def make_T(R: np.ndarray, t: np.ndarray) -> np.ndarray:
    T = np.eye(4, dtype=float)
    T[:3, :3] = np.asarray(R, dtype=float).reshape(3, 3)
    T[:3, 3] = np.asarray(t, dtype=float).reshape(3)
    return T


def transform_points(points: np.ndarray, R: np.ndarray, t: np.ndarray) -> np.ndarray:
    pts = np.asarray(points, dtype=float)
    return (R @ pts.T).T + t.reshape(1, 3)


def transform_dirs(dirs: np.ndarray, R: np.ndarray) -> np.ndarray:
    arr = np.asarray(dirs, dtype=float)
    if arr.ndim == 1:
        return R @ arr
    return (R @ arr.T).T


def bbox_from_points(points: np.ndarray):
    pts = np.asarray(points, dtype=float)
    bmin = pts.min(axis=0)
    bmax = pts.max(axis=0)
    center = 0.5 * (bmin + bmax)
    size = bmax - bmin
    return bmin, bmax, center, size


def read_mesh(path: Path) -> o3d.geometry.TriangleMesh:
    mesh = o3d.io.read_triangle_mesh(str(path))
    if len(mesh.vertices) == 0 or len(mesh.triangles) == 0:
        raise RuntimeError(f"Empty mesh: {path}")
    return mesh


def write_mesh_with_transform(input_path: Path, output_path: Path, R: np.ndarray, t: np.ndarray):
    mesh = read_mesh(input_path)
    v = np.asarray(mesh.vertices, dtype=float)
    mesh.vertices = o3d.utility.Vector3dVector(transform_points(v, R, t))
    mesh.compute_vertex_normals()
    ok = o3d.io.write_triangle_mesh(str(output_path), mesh)
    if not ok:
        raise RuntimeError(f"Failed to write mesh: {output_path}")
    return mesh


def write_pcd_with_transform(input_path: Path, output_path: Path, R: np.ndarray, t: np.ndarray):
    if not input_path.exists():
        return ""
    pcd = o3d.io.read_point_cloud(str(input_path))
    pts = np.asarray(pcd.points, dtype=float)
    if len(pts) == 0:
        return ""
    pcd.points = o3d.utility.Vector3dVector(transform_points(pts, R, t))
    o3d.io.write_point_cloud(str(output_path), pcd)
    return str(output_path)


def transform_plane(plane_model: np.ndarray, R: np.ndarray, t: np.ndarray) -> np.ndarray:
    """
    Original plane: n^T p + d = 0.
    New point: q = R p + t.
    New plane: (R n)^T q + (d - (R n)^T t) = 0.
    """
    p = np.asarray(plane_model, dtype=float).reshape(4)
    n = p[:3]
    d = float(p[3])
    s = np.linalg.norm(n)
    if s < 1e-12:
        raise ValueError(f"Invalid plane model: {plane_model}")
    n = n / s
    d = d / s
    n_new = R @ n
    d_new = d - float(n_new @ t)
    return np.r_[n_new, d_new]


def orient_plane_to_normal(plane_model: np.ndarray, target_normal: np.ndarray) -> np.ndarray:
    p = np.asarray(plane_model, dtype=float).reshape(4)
    n = normalize(p[:3])
    d = float(p[3]) / np.linalg.norm(p[:3])
    p = np.r_[n, d]
    if float(p[:3] @ normalize(target_normal)) < 0:
        p = -p
    return p


def to_jsonable(x: Any):
    if isinstance(x, np.ndarray):
        return x.tolist()
    if isinstance(x, (np.float32, np.float64)):
        return float(x)
    if isinstance(x, (np.int32, np.int64)):
        return int(x)
    if isinstance(x, Path):
        return str(x)
    return x


# =========================================================
# Rotation construction
# =========================================================
def make_rotation_from_top_side(top_n_inward: np.ndarray, side_n_inward: np.ndarray):
    """
    Construct R for column-vector transform p_new = R @ p_old + t.

    Enforced:
        R @ top_n_inward = [0, 0, 1]
        R @ side_n_inward ~= [0, 1, 0]

    If top_n and side_n are not exactly perpendicular, side_n is projected to
    the plane perpendicular to top_n. This keeps top plane exactly parallel to XOY.
    """
    z_src = normalize(top_n_inward)

    y_src_raw = normalize(side_n_inward)
    y_src = y_src_raw - float(y_src_raw @ z_src) * z_src
    y_src = normalize(y_src)
    if float(y_src @ y_src_raw) < 0:
        y_src = -y_src

    x_src = normalize(np.cross(y_src, z_src))

    # Source basis columns are old-frame directions that should become +X,+Y,+Z.
    S = np.column_stack([x_src, y_src, z_src])
    R = S.T

    # Numerical cleanup: nearest proper rotation.
    U, _, Vt = np.linalg.svd(R)
    R = U @ Vt
    if np.linalg.det(R) < 0:
        U[:, -1] *= -1
        R = U @ Vt

    source_basis = np.column_stack([x_src, y_src, z_src])
    return R, source_basis


