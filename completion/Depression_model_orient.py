#   "keep_z_y"    -> enforce +Z=-n_axis and +Y=-max_u_outward, compute +X by right-hand rule
#   "keep_z_x"    -> enforce +Z=-n_axis and +X=-max_v_outward, compute +Y by right-hand rule
HANDEDNESS_MODE = "keep_z_y"


