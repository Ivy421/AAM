def read_mesh_vertices(mesh_path: Path) -> Tuple[o3d.geometry.TriangleMesh, np.ndarray]:
    mesh = o3d.io.read_triangle_mesh(str(mesh_path))
    if len(mesh.vertices) == 0:
        raise RuntimeError(f"Empty STL mesh: {mesh_path}")
    vertices = np.asarray(mesh.vertices, dtype=np.float64)
    return mesh, vertices


def transform_mesh_file(input_path: Path, output_path: Path, T: np.ndarray) -> None:
    mesh = o3d.io.read_triangle_mesh(str(input_path))
    if len(mesh.vertices) == 0:
        print(f"[warn] skip empty mesh: {input_path}")
        return
    vertices = np.asarray(mesh.vertices, dtype=np.float64)
    vertices_out = apply_T_to_points(vertices, T)
    mesh.vertices = o3d.utility.Vector3dVector(vertices_out)
    mesh.compute_vertex_normals()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    ok = o3d.io.write_triangle_mesh(str(output_path), mesh, write_ascii=False)
    if not ok:
        raise RuntimeError(f"Failed to write mesh: {output_path}")
    print(f"[saved] transformed mesh: {output_path}")


def transform_pcd_file(input_path: Path, output_path: Path, T: np.ndarray) -> None:
    pcd = o3d.io.read_point_cloud(str(input_path))
    if len(pcd.points) == 0:
        print(f"[warn] skip empty point cloud: {input_path}")
        return
    points = np.asarray(pcd.points, dtype=np.float64)
    pcd.points = o3d.utility.Vector3dVector(apply_T_to_points(points, T))

    # Normals are vectors, so only rotate them.
    if pcd.has_normals():
        normals = np.asarray(pcd.normals, dtype=np.float64)
        pcd.normals = o3d.utility.Vector3dVector(apply_R_to_vectors(normals, T[:3, :3]))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    ok = o3d.io.write_point_cloud(str(output_path), pcd)
    if not ok:
        raise RuntimeError(f"Failed to write point cloud: {output_path}")
    print(f"[saved] transformed point cloud: {output_path}")


def oriented_extra_name(path: Path) -> str:
    return path.stem + "_oriented" + path.suffix


def transform_extra_geometries(completion_dir: Path, input_main_stl: Path, T: np.ndarray) -> List[str]:
    saved: List[str] = []
    if not TRANSFORM_EXTRA_GEOMETRIES:
        return saved

    for name in EXTRA_GEOMETRY_NAMES:
        p = completion_dir / name
        if not p.exists():
            continue
        if p.resolve() == input_main_stl.resolve():
            continue

        out = completion_dir / oriented_extra_name(p)
        suffix = p.suffix.lower()
        try:
            if suffix == ".stl":
                transform_mesh_file(p, out, T)
                saved.append(str(out))
            elif suffix in {".pcd", ".ply", ".xyz", ".xyzn", ".xyzrgb"}:
                transform_pcd_file(p, out, T)
                saved.append(str(out))
        except Exception as e:
            print(f"[warn] failed to transform {p}: {e}")

    return saved


