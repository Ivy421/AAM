def main():
    meta = load_meta(META_PATH)

    n_axis = normalize(meta["n_axis"])
    h_axis = -n_axis
    attach_center = meta["attach_center"]
    u_axis, v_axis = recover_uv_axes(meta)

    if not os.path.exists(INPUT_STL):
        raise FileNotFoundError(f"Cannot find input STL from repairModel_mesh.py: {INPUT_STL}")

    model_mesh = trimesh.load(INPUT_STL, force="mesh", process=True)
    model_mesh = force_consistent_positive_volume(clean_trimesh(model_mesh))
    if len(model_mesh.vertices) == 0:
        raise RuntimeError(f"Empty mesh: {INPUT_STL}")
    model_mesh.vertex_normals

    gripper_mesh, loft_sections, vneck_s0, vneck_s1, grip_s1 = create_gripper_loft_mesh(
        surface_center=attach_center,
        u_axis=u_axis,
        v_axis=v_axis,
        h_axis=h_axis,
    )

    print("model watertight:", model_mesh.is_watertight)
    print("model volume:", model_mesh.is_volume)
    print("model winding consistent:", model_mesh.is_winding_consistent)

    print("gripper watertight:", gripper_mesh.is_watertight)
    print("gripper volume:", gripper_mesh.is_volume)
    print("gripper winding consistent:", gripper_mesh.is_winding_consistent)
    print("gripper loft section count:", len(loft_sections))

    if BOOLEAN is True:
        # 这个函数让 GRIP 与 repair model 不再是两个分割的实体，拼成一个整体。
        full_mesh = boolean_union(model_mesh, gripper_mesh)
    elif BOOLEAN is False:
        # 保持原逻辑：不做 boolean，只把两个 mesh 写在同一个 STL 中。
        full_mesh = merge_meshes([model_mesh, gripper_mesh])
    else:
        raise ValueError("BOOLEAN must be True or False")

    os.makedirs(COMPLETION_DIR, exist_ok=True)
    #ok1 = o3d.io.write_triangle_mesh(GRIPPER_ONLY_STL, gripper_mesh)
    #ok2 = o3d.io.write_triangle_mesh(OUTPUT_STL, full_mesh)
    gripper_mesh.export(GRIPPER_ONLY_STL)
    full_mesh.export(OUTPUT_STL)

    np.savez(
        GRIPPER_META,
        attach_center=attach_center,
        n_axis=n_axis,
        h_axis=h_axis,
        u_axis=u_axis,
        v_axis=v_axis,
        mm=float(MM),
        embed_depth=float(EMBED_DEPTH),
        base_height=float(BASE_HEIGHT),
        base_width_u=float(BASE_WIDTH_U),
        base_length_v=float(BASE_LENGTH_V),
        v_neck_start_height=float(vneck_s0),
        v_neck_height=float(V_NECK_HEIGHT),
        v_neck_end_height=float(vneck_s1),
        v_neck_min_width_u=float(V_NECK_MIN_WIDTH_U),
        v_neck_min_length_v=float(V_NECK_MIN_LENGTH_V),
        v_neck_section_num=int(V_NECK_SECTION_NUM),
        grip_body_height=float(GRIP_BODY_HEIGHT),
        grip_body_width_u=float(GRIP_BODY_WIDTH_U),
        grip_body_length_v=float(GRIP_BODY_LENGTH_V),
        grip_top_height=float(grip_s1),
        loft_sections=np.asarray(loft_sections, dtype=float),
        output_stl=OUTPUT_STL,
        gripper_only_stl=GRIPPER_ONLY_STL,
        boolean=bool(BOOLEAN),
    )

    print("\n========== Depression gripper generation loft done ==========")
    print("input model STL:", INPUT_STL)
    print("output STL:", OUTPUT_STL)
    print("gripper only STL:", GRIPPER_ONLY_STL)
    print("gripper meta:", GRIPPER_META)
    print("attach center:", attach_center)
    print("height direction h_axis = -n_axis:", h_axis)
    print("width direction u_axis:", u_axis)
    print("length direction v_axis:", v_axis)
    print("V-neck starts at:", vneck_s0, "model unit")
    print("V-neck ends at:", vneck_s1, "model unit")
    print("V-neck waist size [u, v]:", V_NECK_MIN_WIDTH_U, V_NECK_MIN_LENGTH_V)
    print("Grip top height:", grip_s1, "model unit")

    if VISUALIZE:
        model_show = o3d.geometry.TriangleMesh(model_mesh)
        gripper_show = o3d.geometry.TriangleMesh(gripper_mesh)

        model_show.paint_uniform_color([0.65, 0.65, 0.65])
        gripper_show.paint_uniform_color([0.65, 0.65, 0.65])

        frame = o3d.geometry.TriangleMesh.create_coordinate_frame(size=0.06)
        o3d.visualization.draw_geometries(
            [model_show, gripper_show, frame]
        )


def parse_args():
    parser = argparse.ArgumentParser(description="Generate depression gripper mesh.")
    parser.add_argument("--completion-dir", type=str, default=None, help="Completion output directory.")
    parser.add_argument("--input-stl", type=str, default=None, help="Input repair model STL.")
    parser.add_argument("--meta", type=str, default=None, help="Input completion meta.npz.")
    parser.add_argument("--output-stl", type=str, default=None, help="Output model_with_gripper STL.")
    parser.add_argument("--gripper-only-stl", type=str, default=None, help="Output gripper-only STL.")
    parser.add_argument("--gripper-meta", type=str, default=None, help="Output gripper_meta.npz.")
    parser.add_argument("--visualize", action="store_true", help="Show Open3D visualization.")
    parser.add_argument("--no-boolean", action="store_true", help="Concatenate model and gripper instead of boolean union.")
    return parser.parse_args()


def configure_from_args(args):
    global COMPLETION_DIR, INPUT_STL, META_PATH, OUTPUT_STL
    global GRIPPER_ONLY_STL, GRIPPER_META, VISUALIZE, BOOLEAN

    if args.completion_dir is not None:
        COMPLETION_DIR = args.completion_dir
        INPUT_STL = os.path.join(COMPLETION_DIR, "model_processed.stl")
        META_PATH = os.path.join(COMPLETION_DIR, "meta.npz")
        OUTPUT_STL = os.path.join(COMPLETION_DIR, "model_with_gripper.stl")
        GRIPPER_ONLY_STL = os.path.join(COMPLETION_DIR, "gripper_only.stl")
        GRIPPER_META = os.path.join(COMPLETION_DIR, "gripper_meta.npz")
    if args.input_stl is not None:
        INPUT_STL = args.input_stl
    if args.meta is not None:
        META_PATH = args.meta
    if args.output_stl is not None:
        OUTPUT_STL = args.output_stl
    if args.gripper_only_stl is not None:
        GRIPPER_ONLY_STL = args.gripper_only_stl
    if args.gripper_meta is not None:
        GRIPPER_META = args.gripper_meta
    if args.visualize:
        VISUALIZE = True
    if args.no_boolean:
        BOOLEAN = False


if __name__ == "__main__":
    configure_from_args(parse_args())
    main()
