# Main
# =========================================================
def main():
    COMPLETION_DIR.mkdir(parents=True, exist_ok=True)

    gripper_meta = np.load(str(GRIPPER_META_PATH), allow_pickle=True)
    meta = np.load(str(META_PATH), allow_pickle=True)

    top_id = int(gripper_meta["top_id"])
    side_id = int(gripper_meta["side_id"])
    top_n = normalize(gripper_meta["top_n_inward"])
    side_n = normalize(gripper_meta["side_n_inward"])

    R, source_basis = make_rotation_from_top_side(top_n, side_n)

    # Read and rotate the full model with gripper. No unit scale is used.
    full_mesh = read_mesh(INPUT_FULL_STL)
    vertices = np.asarray(full_mesh.vertices, dtype=float)
    vertices_rot = (R @ vertices.T).T

    bbox_min_rot, bbox_max_rot, bbox_center_rot, bbox_size_rot = bbox_from_points(vertices_rot)
    t = -bbox_center_rot
    vertices_out = vertices_rot + t.reshape(1, 3)

    T = make_T(R, t)
    T_inv = np.linalg.inv(T)

    full_mesh.vertices = o3d.utility.Vector3dVector(vertices_out)
    full_mesh.compute_vertex_normals()
    o3d.io.write_triangle_mesh(str(OUTPUT_FULL_STL), full_mesh)
    #o3d.io.write_triangle_mesh(str(OUTPUT_FULL_STL_ALIAS), full_mesh)

    bbox_min_after, bbox_max_after, bbox_center_after, bbox_size_after = bbox_from_points(vertices_out)

    # Transform repair-only and gripper-only STL for debugging / downstream use.
    repair_bbox_center_after = np.full(3, np.nan)
    repair_bbox_min_after = np.full(3, np.nan)
    repair_bbox_max_after = np.full(3, np.nan)
    full_T_repair = np.eye(4)

    if INPUT_REPAIR_STL.exists():
        repair_mesh = write_mesh_with_transform(INPUT_REPAIR_STL, OUTPUT_REPAIR_STL, R, t)
        repair_vertices_out = np.asarray(repair_mesh.vertices, dtype=float)
        repair_bbox_min_after, repair_bbox_max_after, repair_bbox_center_after, _ = bbox_from_points(repair_vertices_out)
        full_T_repair[:3, 3] = repair_bbox_center_after

    if INPUT_GRIPPER_STL.exists():
        write_mesh_with_transform(INPUT_GRIPPER_STL, OUTPUT_GRIPPER_STL, R, t)

    # Transform common point clouds saved by previous steps.
    oriented_pcd_paths: Dict[str, str] = {}
    for name in ["model", "defect_pcd1", "defect_pcd2", "plane1_pcd", "plane2_pcd"]:
        in_p = COMPLETION_DIR / f"{name}.pcd"
        out_p = COMPLETION_DIR / f"{name}_oriented.pcd"
        out = write_pcd_with_transform(in_p, out_p, R, t)
        if out:
            oriented_pcd_paths[name] = out

    # Transform key points from gripper_meta.
    edge_mid = np.asarray(gripper_meta["edge_mid"], dtype=float).reshape(3)
    root_points = np.asarray(gripper_meta["root_points"], dtype=float).reshape(-1, 3)
    edge_mid_oriented = R @ edge_mid + t
    root_points_oriented = transform_points(root_points, R, t)

    frame_T = np.asarray(gripper_meta["frame_T"], dtype=float).reshape(4, 4)
    frame_T_oriented = T @ frame_T

    # Transform key points and planes from Hole_Completion meta.
    plane1_model_oriented = transform_plane(meta["plane1_model"], R, t)
    plane2_model_oriented = transform_plane(meta["plane2_model"], R, t)
    top_plane_oriented = transform_plane(meta[f"plane{top_id}_model"], R, t)
    side_plane_oriented = transform_plane(meta[f"plane{side_id}_model"], R, t)

    plane1_center_oriented = R @ np.asarray(meta["plane1_center"], dtype=float).reshape(3) + t
    plane2_center_oriented = R @ np.asarray(meta["plane2_center"], dtype=float).reshape(3) + t
    object_center_oriented = R @ np.asarray(meta["object_center"], dtype=float).reshape(3) + t
    defect1_center_oriented = R @ np.asarray(meta["defect1_center"], dtype=float).reshape(3) + t
    defect2_center_oriented = R @ np.asarray(meta["defect2_center"], dtype=float).reshape(3) + t

    # Save everything needed for downstream transform tracking.
    np.savez(
        str(ORIENTATION_META_PATH),
        T=T,
        T_inv=T_inv,
        R=R,
        t=t,
        input_full_stl=str(INPUT_FULL_STL),
        output_full_stl=str(OUTPUT_FULL_STL),
        output_full_stl_alias=str(OUTPUT_FULL_STL_ALIAS),
        input_repair_stl=str(INPUT_REPAIR_STL),
        output_repair_stl=str(OUTPUT_REPAIR_STL),
        input_gripper_stl=str(INPUT_GRIPPER_STL),
        output_gripper_stl=str(OUTPUT_GRIPPER_STL),
        meta_path=str(META_PATH),
        gripper_meta_path=str(GRIPPER_META_PATH),
        unit_scale=1.0,
        top_id=top_id,
        side_id=side_id,
        top_n_inward=top_n,
        side_n_inward=side_n,
        x_axis_src=source_basis[:, 0],
        y_axis_src=source_basis[:, 1],
        z_axis_src=source_basis[:, 2],
        top_n_after=R @ top_n,
        side_n_after=R @ side_n,
        bbox_min_rot=bbox_min_rot,
        bbox_max_rot=bbox_max_rot,
        bbox_center_rot=bbox_center_rot,
        bbox_size_rot=bbox_size_rot,
        bbox_min_after=bbox_min_after,
        bbox_max_after=bbox_max_after,
        bbox_center_after=bbox_center_after,
        bbox_size_after=bbox_size_after,
        full_box_x=float(bbox_size_after[0]),
        full_box_y=float(bbox_size_after[1]),
        full_box_z=float(bbox_size_after[2]),
        repair_bbox_min_after=repair_bbox_min_after,
        repair_bbox_max_after=repair_bbox_max_after,
        repair_bbox_center_after=repair_bbox_center_after,
        full_T_repair=full_T_repair,
        repair_T_full=np.linalg.inv(full_T_repair),
        edge_mid=edge_mid,
        edge_mid_oriented=edge_mid_oriented,
        root_points=root_points,
        root_points_oriented=root_points_oriented,
        frame_T=frame_T,
        frame_T_oriented=frame_T_oriented,
        plane1_model=meta["plane1_model"],
        plane2_model=meta["plane2_model"],
        plane1_model_oriented=plane1_model_oriented,
        plane2_model_oriented=plane2_model_oriented,
        top_plane_oriented=top_plane_oriented,
        side_plane_oriented=side_plane_oriented,
        plane1_center_oriented=plane1_center_oriented,
        plane2_center_oriented=plane2_center_oriented,
        object_center_oriented=object_center_oriented,
        defect1_center_oriented=defect1_center_oriented,
        defect2_center_oriented=defect2_center_oriented,
        oriented_model_pcd_path=oriented_pcd_paths.get("model", ""),
        oriented_defect_pcd1_path=oriented_pcd_paths.get("defect_pcd1", ""),
        oriented_defect_pcd2_path=oriented_pcd_paths.get("defect_pcd2", ""),
        oriented_plane1_pcd_path=oriented_pcd_paths.get("plane1_pcd", ""),
        oriented_plane2_pcd_path=oriented_pcd_paths.get("plane2_pcd", ""),
    )

    summary = {
        "input_full_stl": str(INPUT_FULL_STL),
        "output_full_stl": str(OUTPUT_FULL_STL),
        "output_full_stl_alias": str(OUTPUT_FULL_STL_ALIAS),
        "orientation_meta": str(ORIENTATION_META_PATH),
        "unit_scale": 1.0,
        "top_id": top_id,
        "side_id": side_id,
        "top_n_after": R @ top_n,
        "side_n_after": R @ side_n,
        "bbox_min_after": bbox_min_after,
        "bbox_max_after": bbox_max_after,
        "bbox_center_after": bbox_center_after,
        "bbox_size_after": bbox_size_after,
        "T": T,
        "full_T_repair": full_T_repair,
        "edge_mid_oriented": edge_mid_oriented,
        "root_points_oriented": root_points_oriented,
    }
    with open(ORIENTATION_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump({k: to_jsonable(v) for k, v in summary.items()}, f, indent=2, ensure_ascii=False)

    print("\n========== hole model orientation done ==========")
    print("input full STL:", INPUT_FULL_STL)
    print("output full STL:", OUTPUT_FULL_STL)
    print("output alias:", OUTPUT_FULL_STL_ALIAS)
    print("orientation meta:", ORIENTATION_META_PATH)
    print("unit_scale: 1.0, no unit conversion")
    print("top_n_after:", R @ top_n)
    print("side_n_after:", R @ side_n)
    print("bbox_center_after:", bbox_center_after)
    print("bbox_size_after:", bbox_size_after)
    print("T:\n", T)

    if VISUALIZE:
        mesh_show = o3d.geometry.TriangleMesh(full_mesh)
        mesh_show.paint_uniform_color([0.7, 0.7, 0.7])
        frame = o3d.geometry.TriangleMesh.create_coordinate_frame(size=max(0.02, float(np.linalg.norm(bbox_size_after)) * 0.25))
        o3d.visualization.draw_geometries([mesh_show, frame])


if __name__ == "__main__":
    main()
