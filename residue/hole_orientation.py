def normalize(v: np.ndarray, name: str = "vector") -> np.ndarray:
    v = np.asarray(v, dtype=np.float64).reshape(3)
    n = np.linalg.norm(v)
    if n < 1e-12:
        raise ValueError(f"{name} is zero-length: {v}")
    return v / n


def make_T(R: np.ndarray, t: np.ndarray) -> np.ndarray:
    T = np.eye(4, dtype=np.float64)
    T[:3, :3] = np.asarray(R, dtype=np.float64).reshape(3, 3)
    T[:3, 3] = np.asarray(t, dtype=np.float64).reshape(3)
    return T


def apply_T_to_points(points: np.ndarray, T: np.ndarray) -> np.ndarray:
    points = np.asarray(points, dtype=np.float64)
    if points.ndim == 1:
        return T[:3, :3] @ points.reshape(3) + T[:3, 3]
    return (T[:3, :3] @ points.T).T + T[:3, 3].reshape(1, 3)


def apply_R_to_vectors(vectors: np.ndarray, R: np.ndarray) -> np.ndarray:
    vectors = np.asarray(vectors, dtype=np.float64)
    if vectors.ndim == 1:
        return R @ vectors.reshape(3)
    return (R @ vectors.T).T


def unwrap_np_value(x: Any) -> Any:
    """Convert numpy scalar/object array to normal Python value when possible."""
    if isinstance(x, np.ndarray):
        if x.shape == ():
            return x.item()
    return x


def to_jsonable(x: Any) -> Any:
    if isinstance(x, np.ndarray):
        return x.tolist()
    if isinstance(x, (np.integer, np.floating)):
        return x.item()
    if isinstance(x, Path):
        return str(x)
    if isinstance(x, dict):
        return {str(k): to_jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [to_jsonable(v) for v in x]
    return x


